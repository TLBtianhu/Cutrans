"""Build the single-file payload blob and its Zig embed declaration.

The input directories are the already-verified payload packs (desktop and
nanoui-library). The output is one deterministic blob plus a tiny Zig module
that embeds it. Runtime extraction and verification stay in bootstrap.
"""

from __future__ import annotations

import argparse
import hashlib
import struct
from pathlib import Path

MAGIC = b"CTPE1\x00\x00\x00"


def entries(directory: Path, prefix: str):
    for path in sorted(p for p in directory.rglob("*") if p.is_file()):
        relative = path.relative_to(directory).as_posix()
        yield prefix + "/" + relative, path.read_bytes()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--desktop", type=Path, required=True)
    parser.add_argument("--library", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, required=True)
    args = parser.parse_args()

    all_entries = list(entries(args.desktop, "desktop")) + list(entries(args.library, "nanoui-library"))
    blob = bytearray(MAGIC)
    blob += struct.pack("<I", len(all_entries))
    for name, data in all_entries:
        encoded = name.encode("utf-8")
        if len(encoded) > 0xFFFF:
            raise SystemExit("payload path is too long")
        blob += struct.pack("<H", len(encoded))
        blob += encoded
        blob += struct.pack("<I", len(data))
        blob += data

    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "payload.bin").write_bytes(blob)
    digest = hashlib.sha256(blob).hexdigest()
    (args.out_dir / "payload_blob.zig").write_text(
        "// Generated by tools/build_payload_embed.py. Do not edit.\n"
        'pub const bytes = @embedFile("payload.bin");\n'
        f'pub const id = "{digest}";\n',
        encoding="utf-8",
    )
    print(f"payload embed: {len(all_entries)} files, {len(blob)} bytes, {digest}")


if __name__ == "__main__":
    main()
