"""Source-package guard negative cases; no product processes or downloads."""
from __future__ import annotations

import json
from pathlib import Path
import stat
from types import SimpleNamespace
import unittest
from unittest.mock import patch

import repository_audit as guard
from verification_paths import claim, default_root, retain


class RepositoryAuditTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.root = claim(default_root("repository-audit"))
        retain(cls.root)

    @classmethod
    def tearDownClass(cls):
        print(f"Repository guard fixtures retained: {cls.root}")

    def fixture(self, name, extra=()):
        root = self.root / name
        root.mkdir()
        files = {"build.zig": "pub fn build(_: *anyopaque) void {}\n", "README.md": "# Fixture\n",
            "LICENSE": "owned fixture\n", ".gitignore": "zig-out/\n",
            "dependencies.lock.json": json.dumps({"format": "cutrans-dependencies/1", "sources": []})}
        for relative, content in files.items():
            (root / relative).write_text(content, encoding="utf-8")
        self.manifest(root, [*files, "build.zig.zon", *extra])
        return root

    def manifest(self, root, paths, dependency=""):
        values = ", ".join(json.dumps(path) for path in paths)
        (root / "build.zig.zon").write_text(f".{{ .name = .fixture, {dependency} .paths = .{{ {values} }}, }}\n", encoding="utf-8")

    def report(self, root):
        result = guard.audit(root, git=False)
        (root / "audit-evidence.txt").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
        return result

    def test_literal_paths_ignore_comment_traps_and_reject_expressions_or_traversal(self):
        self.assertEqual(guard.zon_paths('// .paths = .{ "wrong" };\n.{ .paths = .{ "build.zig", "tools/helper.py", }, }'),
            ["build.zig", "tools/helper.py"])
        for text in ('.{ .paths = .{ "../escape" } }', '.{ .paths = .{ "tools\\\\zig" } }',
                     '.{ .paths = .{ prefix ++ "file" } }', '.{ .paths = .{} }'):
            with self.subTest(text=text), self.assertRaises(guard.AuditError):
                guard.zon_paths(text)

    def test_unlisted_build_tool_and_local_python_import_are_not_hidden_by_present_files(self):
        root = self.fixture("missing-tool", ("tools/main.py",))
        (root / "tools").mkdir()
        (root / "tools/main.py").write_text("import local_helper\n", encoding="utf-8")
        (root / "tools/local_helper.py").write_text("VALUE = 1\n", encoding="utf-8")
        (root / "build.zig").write_text('pub fn build(b: *anyopaque) void { _ = b.path("tools/missing.py"); }\n', encoding="utf-8")
        result = self.report(root)
        failures = {(value["code"], value["path"]) for value in result["failures"]}
        self.assertFalse(result["passed"])
        self.assertIn(("unpackaged_local_input", "tools/local_helper.py"), failures)
        self.assertIn(("missing_local_input", "tools/missing.py"), failures)

    def test_broad_tools_selection_rejected_even_before_toolchain_is_downloaded(self):
        root = self.fixture("broad-tools", ("tools",))
        (root / "tools").mkdir()
        (root / "tools/helper.py").write_text("VALUE = 1\n", encoding="utf-8")
        result = self.report(root)
        self.assertFalse(result["passed"])
        self.assertTrue(any(value["code"] == "broad_restored_root" and value["path"] == "tools" for value in result["failures"]))
        self.assertEqual(guard.forbidden("tools/zig/lib/std/std.zig"), "restored toolchain/native directory")
        self.assertEqual(guard.forbidden("apps/__pycache__/old.pyc"), "generated/cache directory")
        self.assertEqual(guard.forbidden("runtime/accidental.dll"), "native binary or Python bytecode")
        self.assertEqual(guard.forbidden("config/startup.ccb"), "generated source-tree output")
        self.assertEqual(guard.forbidden("apps/desktop/assets/ui/desktop.cui"), "generated source-tree output")
        self.assertEqual(guard.zig_inputs("apps/desktop/view.zig", 'const data = @embedFile("desktop_cui");'),
            [(".", "apps/desktop/assets/ui/compile_ui.py")])
        (root / "config").mkdir()
        (root / "config/startup.ccb").write_bytes(b"owned stale generated output")
        result = self.report(root)
        self.assertTrue(any(value["code"] == "generated_source_output_present" and value["path"] == "config/startup.ccb"
            for value in result["failures"]), "untracked/unselected generated bytes were silently accepted")

    def test_parent_reparse_is_rejected_before_statting_any_child(self):
        root = self.fixture("parent-link")
        link = root / "linked-parent"
        link.mkdir()
        visited, original = [], Path.lstat

        def metadata(path):
            visited.append(path)
            return SimpleNamespace(st_mode=stat.S_IFLNK, st_file_attributes=0x400) if path == link else original(path)

        with patch.object(Path, "lstat", metadata), self.assertRaisesRegex(guard.AuditError, "link or junction"):
            guard.safe_path(root, "linked-parent/must-not-be-statted.txt")
        self.assertIn(link, visited)
        self.assertNotIn(link / "must-not-be-statted.txt", visited)

    def test_markdown_memory_links_are_checked_but_historical_machine_paths_are_never_opened(self):
        root = self.fixture("markdown", ("docs",))
        (root / "docs/memory").mkdir(parents=True)
        (root / "docs/含空格 file.md").write_text("# Target\n", encoding="utf-8")
        (root / "docs/memory/current.md").write_text(
            "[local](../%E5%90%AB%E7%A9%BA%E6%A0%BC%20file.md#section)\n"
            "[historic](C:/private/not-present.md)\n[missing](../missing.md)\n"
            "```md\n[example](not-an-actual-link.md)\n```\n", encoding="utf-8")
        result = self.report(root)
        self.assertFalse(result["passed"])
        self.assertEqual(result["markdown"]["historical_absolute_links"], 1)
        missing = [value for value in result["failures"] if value["code"] == "missing_local_input"]
        self.assertEqual([value["path"] for value in missing], ["docs/missing.md"])

    def test_complete_extracted_source_resolves_local_sibling_dependency_without_git(self):
        root = self.fixture("source-archive", ("third_party/a", "third_party/b"))
        paths = guard.zon_paths((root / "build.zig.zon").read_text(encoding="utf-8"))
        self.manifest(root, paths, '.dependencies = .{ .a = .{ .path = "third_party/a" }, },')
        for name, dependency in (("a", '.dependencies = .{ .b = .{ .path = "../b" }, },'), ("b", "")):
            base = root / "third_party" / name
            base.mkdir(parents=True)
            (base / "build.zig").write_text("pub fn build(_: *anyopaque) void {}\n", encoding="utf-8")
            (base / "build.zig.zon").write_text(f'.{{ {dependency} .paths = .{{ "build.zig", "build.zig.zon" }}, }}\n', encoding="utf-8")
        result = self.report(root)
        self.assertTrue(result["passed"], result["failures"])
        self.assertFalse(result["git"]["checked"])
        self.assertEqual(result["local_dependency_packages"], 2)

    def test_build_dependency_receiver_is_relative_to_package_and_runtime_format_is_not_a_file(self):
        code = '''pub fn build(b: *anyopaque) void {
            const zgui_dep = b.dependency("zgui", .{});
            _ = zgui_dep.path("libs/imgui/backends/imgui_impl_glfw.cpp");
            _ = b.path("tools/missing.py");
            const sources = .{ .{ "assets/required.png", "portable/assets/required.png" } };
            _ = b.fmt("third_party/wgpu/lib;{s}", .{ "inherited PATH" });
        }'''
        dependencies = guard.zon_dependencies('.{ .dependencies = .{ .zgui = .{ .path = "third_party/zgui" }, }, .paths = .{ "build.zig" }, }')
        inputs = guard.zig_inputs("build.zig", code, dependencies)
        self.assertIn(("third_party/zgui", "libs/imgui/backends/imgui_impl_glfw.cpp"), inputs)
        self.assertIn((".", "tools/missing.py"), inputs)
        self.assertIn((".", "assets/required.png"), inputs)
        self.assertFalse(any(";{s}" in name for _, name in inputs), "runtime format became a source path")
        with self.assertRaisesRegex(guard.AuditError, "unresolved local build path receiver"):
            guard.zig_inputs("build.zig", code, {})

    def test_declared_empty_directory_cannot_pretend_to_be_deliverable_source(self):
        root = self.fixture("empty-declaration", ("third_party/empty-tree",))
        directory = root / "third_party/empty-tree"
        (directory / "nested-empty-child").mkdir(parents=True)
        result = self.report(root)
        self.assertFalse(result["passed"])
        self.assertTrue(any(value["code"] == "empty_declared_directory" and value["path"] == "third_party/empty-tree"
            for value in result["failures"]), "local-only empty directories hid a broken source archive")
        # Zero-byte files are deliverable. This does not require staging a new
        # source file and does not tighten the separate untracked-file policy.
        (directory / "placeholder.txt").write_bytes(b"")
        result = self.report(root)
        self.assertTrue(result["passed"], result["failures"])

    def test_only_exact_archived_concept_expression_is_recorded_instead_of_file(self):
        root = self.fixture("concept-link", ("docs",))
        memory = root / "docs/memory"
        memory.mkdir(parents=True)
        source = memory / "17-discussion-history-02.md"
        source.write_text("[1,2,3,4](四页树 id)\n", encoding="utf-8")
        result = self.report(root)
        self.assertTrue(result["passed"], result["failures"])
        self.assertEqual(result["markdown"]["concept_links"], [{"source": "docs/memory/17-discussion-history-02.md", "expression": "四页树 id"}])
        source.write_text("[1,2,3,4](四页树 id)\n[actual file](四页树)\n", encoding="utf-8")
        result = self.report(root)
        self.assertFalse(result["passed"])
        self.assertTrue(any(value["code"] == "missing_local_input" and value["path"] == "docs/memory/四页树"
            for value in result["failures"]), "all bare historical links were incorrectly exempted")

    def test_packaged_readme_license_link_requires_actual_source_copy_declarations(self):
        root = self.fixture("portable-projection", ("packaging",))
        packaging = root / "packaging"
        packaging.mkdir()
        source = packaging / "README-portable.md"
        source.write_text("[license](licenses/Cutrans.txt)\n", encoding="utf-8")
        build = '''pub fn build(b: *anyopaque) void {
            portable_files.add(b.path("packaging/README-portable.md"), "README.md");
            const portable_notices = .{ .{ "LICENSE", "portable/licenses/Cutrans.txt" } };
        }'''
        (root / "build.zig").write_text(build, encoding="utf-8")
        result = self.report(root)
        self.assertTrue(result["passed"], result["failures"])
        self.assertEqual(result["markdown"]["packaged_output_links"], [{"document": "packaging/README-portable.md", "target": "licenses/Cutrans.txt", "source": "LICENSE"}])
        (root / "build.zig").write_text(build.replace("portable/licenses/Cutrans.txt", "portable/licenses/other.txt"), encoding="utf-8")
        result = self.report(root)
        self.assertFalse(result["passed"])
        self.assertTrue(any(value["code"] == "missing_pack_projection" for value in result["failures"]),
            "missing actual LICENSE copy was hidden by a hardcoded output exception")
        (root / "build.zig").write_text(build, encoding="utf-8")
        source.write_text("[license](licenses/Cutrans.txt)\n[typo](licenses/typo.txt)\n", encoding="utf-8")
        result = self.report(root)
        self.assertFalse(result["passed"])
        self.assertTrue(any(value["code"] == "missing_local_input" and value["path"] == "packaging/licenses/typo.txt"
            for value in result["failures"]), "unrecognized package-output links were silently ignored")


if __name__ == "__main__":
    unittest.main()
