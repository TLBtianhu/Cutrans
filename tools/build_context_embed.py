"""Embed portable and installed run contexts into a tiny Zig module.

The external cutrans-context.json still wins; these only supply the
single-executable fallbacks for portable and installed shapes.
"""

from __future__ import annotations

import argparse
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--portable", type=Path, required=True)
    parser.add_argument("--installed", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, required=True)
    args = parser.parse_args()
    portable = args.portable.read_bytes()
    installed = args.installed.read_bytes()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "portable-context.json").write_bytes(portable)
    (args.out_dir / "installed-context.json").write_bytes(installed)
    (args.out_dir / "context_blob.zig").write_text(
        "// Generated by tools/build_context_embed.py. Do not edit.\n"
        'pub const portable = @embedFile("portable-context.json");\n'
        'pub const installed = @embedFile("installed-context.json");\n',
        encoding="utf-8",
    )
    print(f"context embed: portable={len(portable)} installed={len(installed)} bytes")


if __name__ == "__main__":
    main()
